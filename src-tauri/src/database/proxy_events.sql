-- 详细代理事件沿用旧代理的四方向报文字段，并补充供应商、脚本和重试归属。
-- 同一次客户端请求共用 request_id；一次供应商尝试中的每次上游调用独占一行。
CREATE TABLE IF NOT EXISTS proxy_request_events (
    id INTEGER PRIMARY KEY,
    request_id TEXT NOT NULL,
    app_type TEXT,
    provider_id TEXT,
    session_id TEXT,
    attempt INTEGER NOT NULL DEFAULT 0,
    forward_seq INTEGER NOT NULL DEFAULT 0,
    script_enabled INTEGER NOT NULL DEFAULT 0,
    script_used INTEGER NOT NULL DEFAULT 0,
    request_changed INTEGER NOT NULL DEFAULT 0,
    route_changed INTEGER NOT NULL DEFAULT 0,
    target TEXT NOT NULL,
    upstream TEXT,
    run_at TEXT NOT NULL,
    seq INTEGER NOT NULL,
    started_at TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    duration_ms INTEGER NOT NULL,
    method TEXT NOT NULL,
    url TEXT NOT NULL,
    request_model TEXT,
    model TEXT,
    status INTEGER,
    client_status INTEGER,
    total_bytes INTEGER,
    upstream_header_ms INTEGER,
    upstream_duration_ms INTEGER,
    stream_error TEXT,
    rewritten TEXT,
    error TEXT,
    finish_reason TEXT NOT NULL,
    mods TEXT,
    orig_headers TEXT,
    orig_body TEXT,
    script_url TEXT,
    script_headers TEXT,
    script_body TEXT,
    fwd_url TEXT,
    fwd_method TEXT,
    fwd_headers TEXT,
    fwd_body TEXT,
    resp_headers TEXT,
    resp_body TEXT,
    client_headers TEXT,
    client_body TEXT,
    UNIQUE(request_id, attempt, forward_seq)
) STRICT;
CREATE INDEX IF NOT EXISTS idx_proxy_events_created ON proxy_request_events(created_at);
CREATE INDEX IF NOT EXISTS idx_proxy_events_provider ON proxy_request_events(app_type, provider_id, created_at);
CREATE INDEX IF NOT EXISTS idx_proxy_events_script ON proxy_request_events(script_used, created_at);
CREATE INDEX IF NOT EXISTS idx_proxy_events_status ON proxy_request_events(status, created_at);
